#!/usr/bin/env bash
# Install Formlabs PreForm on Linux under Proton, with a menu entry and a `preform` command.
#
#   curl -fsSL https://github.com/vitaminmoo/preform-on-linux/releases/latest/download/install.sh | bash
#   ... | bash -s -- --beta        public beta instead of the release
#   ... | bash -s -- --uninstall   remove it again (add --beta for the beta)
#
# Environment: PROTONPATH picks the Proton build (default: latest GE-Proton, via umu).
# PREFORM_SHIMS_DIR uses local shim files instead of downloading the release.
set -euo pipefail

REPO_URL=https://github.com/vitaminmoo/preform-on-linux
SHIMS_URL="${PREFORM_SHIMS_URL:-$REPO_URL/releases/latest/download}"
DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
ROOT="$DATA/preform-on-linux"

channel=release
action=install
for arg in "$@"; do
    case "$arg" in
        --beta) channel=beta ;;
        --uninstall) action=uninstall ;;
        -h|--help) sed -n '2,10s/^# \{0,1\}//p' "$0" 2>/dev/null || true; exit 0 ;;
        *) echo "unknown option: $arg" >&2; exit 1 ;;
    esac
done

if [ "$channel" = beta ]; then
    suffix=-beta name="PreForm (Beta)" folder=PreForm-beta
    setup_url=https://downloads.formlabs.com/PreForm/Beta/preform.exe
else
    suffix="" name=PreForm folder=PreForm
    setup_url=https://downloads.formlabs.com/PreForm/Release/preform.exe
fi
prefix="$ROOT/$channel"
# Proton names the window class steam_app_<id> after this, so the menu entry can match it
# (a hyphen in <id> turns the class into steam_app_0, hence the underscore)
gameid="umu-preform${suffix//-/_}"
launcher="$ROOT/bin/preform$suffix"
bin_link="$HOME/.local/bin/preform$suffix"
desktop="$DATA/applications/preform-on-linux$suffix.desktop"
icon="$DATA/icons/hicolor/256x256/apps/preform-on-linux.png"
app_dir="$prefix/drive_c/Program Files/Formlabs/$folder"

say() { printf '\033[1m==> %s\033[0m\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

uninstall() {
    say "Removing $name (prefix, settings and sign-in included)"
    rm -rf "$prefix" "$launcher" "$desktop"
    [ -L "$bin_link" ] && rm -f "$bin_link"
    if [ ! -d "$ROOT/release" ] && [ ! -d "$ROOT/beta" ]; then
        rm -rf "$ROOT" "$icon"
    fi
    command -v update-desktop-database >/dev/null && update-desktop-database -q "$DATA/applications" || true
    say "Done. Proton builds downloaded by umu are left in place."
}

fetch_shims() {
    mkdir -p "$ROOT/shims"
    for f in icuuc.dll dnsapi.dll preform-art.py; do
        if [ -n "${PREFORM_SHIMS_DIR:-}" ]; then
            cp "$PREFORM_SHIMS_DIR/$f" "$ROOT/shims/$f.tmp"
        else
            curl -fsSL -o "$ROOT/shims/$f.tmp" "$SHIMS_URL/$f"
        fi
        mv "$ROOT/shims/$f.tmp" "$ROOT/shims/$f"
    done
}

find_umu() {
    if command -v umu-run >/dev/null; then
        command -v umu-run
        return
    fi
    if [ ! -x "$ROOT/umu/umu-run" ]; then
        say "Downloading umu-launcher (runs Proton outside Steam)" >&2
        local url
        url=$(curl -fsSL https://api.github.com/repos/Open-Wine-Components/umu-launcher/releases/latest \
              | grep -o 'https://[^"]*-zipapp\.tar' | head -n1)
        [ -n "$url" ] || die "couldn't find umu-launcher's zipapp release; install umu-launcher from your distro"
        curl -fsSL "$url" | tar -x -C "$ROOT"
    fi
    echo "$ROOT/umu/umu-run"
}

write_launcher() {
    mkdir -p "$(dirname "$launcher")"
    cat > "$launcher" <<EOF
#!/usr/bin/env bash
# Generated by preform-on-linux install.sh ($REPO_URL)
set -euo pipefail
export WINEPREFIX='$prefix' GAMEID='$gameid' STORE=none
export PROTONPATH="\${PROTONPATH:-GE-Proton}"
# winemenubuilder would add duplicate menu entries from PreForm's Start menu shortcuts
export WINEDLLOVERRIDES="dnsapi=n,b;winemenubuilder.exe=d\${WINEDLLOVERRIDES:+;\$WINEDLLOVERRIDES}"
# Qt WebEngine's Chromium sandbox doesn't work under Wine
export QTWEBENGINE_CHROMIUM_FLAGS="\${QTWEBENGINE_CHROMIUM_FLAGS:---no-sandbox}"
# Qt WebEngine reserves about 32 GiB of address space; lift a soft ulimit -v if there is one
ulimit -Sv unlimited 2>/dev/null || ulimit -Sv "\$(ulimit -Hv)" 2>/dev/null || true

# PreForm updates itself into a new version folder, so keep the dnsapi proxy next to every PreForm.exe
for exe in "\$WINEPREFIX/drive_c/Program Files/Formlabs/"*/*/PreForm.exe; do
    [ -f "\$exe" ] || continue
    dir=\$(dirname "\$exe")
    cmp -s '$ROOT/shims/dnsapi.dll' "\$dir/dnsapi.dll" || cp '$ROOT/shims/dnsapi.dll' "\$dir/"
done

# Files passed in (e.g. from a file manager) need Windows paths; Z: is the root filesystem
args=()
for a in "\$@"; do
    if [ -e "\$a" ]; then
        p=\$(realpath -- "\$a")
        args+=("Z:\${p//\\//\\\\}")
    else
        args+=("\$a")
    fi
done
exec '$umu' "\$WINEPREFIX/drive_c/Program Files/Formlabs/$folder/PreFormLauncher.exe" "\${args[@]}"
EOF
    chmod +x "$launcher"
    mkdir -p "$(dirname "$bin_link")"
    ln -sfn "$launcher" "$bin_link"
}

write_desktop() {
    if command -v python3 >/dev/null; then
        python3 "$ROOT/shims/preform-art.py" --icon "$app_dir/PreFormLauncher.exe" "$icon" >/dev/null \
            || echo "warning: couldn't extract PreForm's icon; the menu entry will use a generic one" >&2
    fi
    mkdir -p "$(dirname "$desktop")"
    cat > "$desktop" <<EOF
[Desktop Entry]
Type=Application
Name=$name
Comment=Formlabs 3D print preparation (via Proton)
Exec="$launcher" %F
Icon=preform-on-linux
Categories=Graphics;3DGraphics;Engineering;
StartupWMClass=steam_app_${gameid#umu-}
Terminal=false
EOF
    command -v update-desktop-database >/dev/null && update-desktop-database -q "$DATA/applications" || true
}

install() {
    for cmd in curl tar cmp realpath; do
        command -v "$cmd" >/dev/null || die "$cmd is required"
    done
    mkdir -p "$ROOT"
    say "Fetching shims"
    fetch_shims
    umu=$(find_umu)

    if [ -f "$app_dir/PreFormLauncher.exe" ]; then
        say "$name is already installed; refreshing shims, launcher and menu entry"
    else
        say "Downloading $name from formlabs.com"
        mkdir -p "$ROOT/cache"
        curl -fL --progress-bar -o "$ROOT/cache/preform$suffix.exe" "$setup_url"
        say "Running the PreForm installer under Proton (first run also downloads Proton)"
        WINEPREFIX="$prefix" GAMEID="$gameid" STORE=none PROTONPATH="${PROTONPATH:-GE-Proton}" \
            WINEDLLOVERRIDES="winemenubuilder.exe=d" \
            "$umu" "$ROOT/cache/preform$suffix.exe" /quiet /norestart
        rm -f "$ROOT/cache/preform$suffix.exe"
        [ -f "$app_dir/PreFormLauncher.exe" ] || die "the PreForm installer didn't produce $app_dir"
    fi

    # Qt6Core imports the Windows 10 system icuuc.dll. GE-Proton 11+ ships one (a symlink
    # into the Proton install, so never write through it); otherwise add our forwarder.
    sys32="$prefix/drive_c/windows/system32"
    [ -e "$sys32/icuuc.dll" ] || [ -L "$sys32/icuuc.dll" ] || cp "$ROOT/shims/icuuc.dll" "$sys32/"
    write_launcher
    write_desktop

    say "Installed. Start $name from your application menu, or run: preform$suffix"
    case ":$PATH:" in
        *":$HOME/.local/bin:"*) ;;
        *) echo "(~/.local/bin isn't on your PATH; run $launcher directly or add it)" ;;
    esac
}

"$action"
