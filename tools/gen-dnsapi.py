#!/usr/bin/env python3
"""Regenerate the dnsapi proxy's export plumbing from a Proton/Wine dnsapi.dll.

Usage: tools/gen-dnsapi.py <proton>/files/lib/wine/x86_64-windows/dnsapi.dll

Writes shims/dnsapi/{dnsapi.def,thunks.S,exports.h}. Every export of the real dnsapi
becomes a `jmp *real[i]` thunk into it, plus the functions mdns.c implements (Proton
doesn't export those at all; Wine 11.13+ exports stubs, which we shadow).
"""
import pathlib
import re
import subprocess
import sys

IMPLEMENTED = {"DnsStartMulticastQuery", "DnsStopMulticastQuery"}
OUT = pathlib.Path(__file__).resolve().parent.parent / "shims" / "dnsapi"


def exports(dll):
    dump = subprocess.run(["objdump", "-p", dll], check=True, capture_output=True, text=True).stdout
    names, in_table = set(), False
    for line in dump.splitlines():
        if "[Ordinal/Name Pointer] Table" in line:
            in_table = True
        elif in_table and "[" in line:
            names.add(line.split()[-1])
        elif in_table and line.strip() == "":
            break
    return sorted(n for n in names if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    real = exports(sys.argv[1])
    if "DnsQuery_W" not in real:
        sys.exit(f"{sys.argv[1]} does not look like dnsapi.dll")
    thunked = [n for n in real if n not in IMPLEMENTED]
    names = sorted(set(real) | IMPLEMENTED)

    (OUT / "dnsapi.def").write_text("LIBRARY dnsapi.dll\nEXPORTS\n" + "".join(f"  {n}\n" for n in names))
    (OUT / "thunks.S").write_text("    .text\n" + "".join(
        f"    .globl {n}\n{n}:\n    jmp *real+{8 * i}(%rip)\n" for i, n in enumerate(thunked)))
    (OUT / "exports.h").write_text(
        "/* Generated by tools/gen-dnsapi.py; do not edit */\n"
        f"#define NUM_THUNKS {len(thunked)}\n"
        "static const char *const names[NUM_THUNKS] = {\n" + "".join(f'    "{n}",\n' for n in thunked) + "};\n")
    print(f"{len(names)} exports, {len(thunked)} thunked")


if __name__ == "__main__":
    main()
